// Copies contract ABIs from Foundry's build output into typed TS modules.
// Run after every contract change:  cd contracts && forge build && cd ../apps/web && npm run abi
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "..", "..", "contracts", "out");
const abiDir = join(here, "..", "lib", "abi");
mkdirSync(abiDir, { recursive: true });

for (const name of ["Competition", "SongRegistry"]) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
  const body =
    `// Generated by scripts/export-abis.mjs from contracts/out/${name}.sol. Do not edit by hand.\n` +
    `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(abiDir, `${name}.ts`), body);
  console.log(`wrote lib/abi/${name}.ts (${artifact.abi.length} entries)`);
}
