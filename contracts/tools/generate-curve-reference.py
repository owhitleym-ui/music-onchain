#!/usr/bin/env python3
"""Regenerate independent, 80-digit reference vectors for the saved curve."""
from decimal import Decimal, ROUND_FLOOR, localcontext
from pathlib import Path

CASES = {
    1: [1], 2: [1, 2], 25: [1, 2, 7, 12, 25],
    50: [1, 2, 13, 25, 50], 100: [1, 2, 3, 8, 50, 100],
    200: [1, 2, 3, 25, 100, 200], 1000: [1, 2, 3, 250, 500, 1000],
}

def reference(n, rank):
    with localcontext() as ctx:
        ctx.prec = 80
        x = min(Decimal(100), 1 + Decimal(100) * (rank - 1) / n)
        weight = Decimal('.40') - Decimal('.20') * (x - 1) / 99
        ratio = (weight * (101 - x) + (1 - weight) * 100 * Decimal('.5') ** (x - 1)) / 100
        return int((ratio * Decimal('.9') * 10**18).to_integral_value(rounding=ROUND_FLOOR))

def main():
    rows = [(n, rank, reference(n, rank)) for n, ranks in CASES.items() for rank in ranks]
    code = '''// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// Generated by contracts/tools/generate-curve-reference.py using Decimal(80).
library CurveReference {
    function vectors() internal pure returns (uint256[] memory counts, uint256[] memory ranks, uint256[] memory ratios) {
'''
    code += f'        counts = new uint256[]({len(rows)});\n        ranks = new uint256[]({len(rows)});\n        ratios = new uint256[]({len(rows)});\n'
    for index, (n, rank, ratio) in enumerate(rows):
        code += f'        counts[{index}] = {n}; ranks[{index}] = {rank}; ratios[{index}] = {ratio};\n'
    code += '    }\n}\n'
    target = Path(__file__).resolve().parents[1] / 'test' / 'fixtures' / 'CurveReference.sol'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(code)

if __name__ == '__main__':
    main()
